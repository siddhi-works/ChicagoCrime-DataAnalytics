"""Generates HANDOFF.md and reports/analysis_report.md from the exported files, so docs can never drift from the data."""
import json

from config import EXPORT, ROOT, REPORTS


def _j(p):
    return json.loads(p.read_text(encoding="utf-8"))


WHY_CHART = {
    "q01": "A line shows ordered, continuous time and makes the repeating seasonal shape and the February dip visible; 28 points is well within what a line can carry.",
    "q02": "Seven discrete ordered categories compared on one measure: columns, in Monday-Sunday order (not alphabetical) so the weekly cycle reads naturally.",
    "q03": "Four ordered parts of the day; columns keep the order Night->Evening and let bar length be compared exactly.",
    "q04": "Four seasons of one year; columns (or a donut) - columns preferred because differences are modest and donut angles are hard to compare.",
    "q05": "Three mutually exclusive parts of one whole - the one case where a donut is justified (share of total).",
    "q06": "A rate for four ordered groups; columns. Shown beside the standardised line so the confounding by crime type is visible.",
    "q07": "Ranked categories with long labels: horizontal bars sorted high to low.",
    "q08": "Same as Q7 for the top 5 domestic types.",
    "q09": "Volume and rate are different units on the same categories, so bars (volume) + line (rate) on a secondary axis show whether busy districts are also high-arrest.",
    "q10": "Two categorical dimensions and a count: a heat map with a colour scale makes the busiest weekday/time cells stand out at a glance.",
}


def write_docs():
    man = _j(EXPORT / "manifest.json")
    ins = _j(EXPORT / "insights.json")
    meth = _j(EXPORT / "methodology.json")
    kpis = _j(EXPORT / "kpis.json")
    charts = [e for e in man["entries"] if e["kind"] == "chart"]

    # ---------------- HANDOFF.md ----------------------------------------------------------------
    L = ["# HANDOFF - for Person 2 (frontend)", "",
         "You only need the `export/` folder. Everything in it is generated by `python run_all.py`; **never copy numbers by hand** - read the JSON.", "",
         "## 1. Start here", "",
         "1. `export/manifest.json` - index of every file (id, path, kind, title, handout ref, recommended chart type, scope, sha256).",
         "2. `export/schemas/types.ts` - TypeScript interfaces (`ChartSpec`, `KPI`, `Insight`, `Cube`, `Manifest`) generated from the same models that validate the data.",
         "3. `export/kpis.json` - the 8 KPI cards (K1-K8) with value, unit, formula, numerator/denominator.",
         "4. `export/charts/*.json` - one file per chart; `data` is a tidy array of records, already sorted/ordered as the handout requires.",
         "5. `export/cube/cube.json(.gz)` / `cube.parquet` - pre-aggregated cube for **filters** (see section 3).",
         "6. `export/insights.json` - ranked findings with text, evidence, linked chart ids and caveats. Use for annotations/story panel.",
         "7. `export/geo/*.json` - map layers derived from the data's own coordinates.", "",
         "## 2. Chart envelope", "",
         "Every `charts/*.json` has: `id, handout_ref, title, chart_type, x{field,label,type}, y{...}, series?, order?, row_field?, note?, window?, scope, filterable_via_cube, caveats[], data[]`.",
         "- `order` gives the category order for ordinal axes (Mon->Sun, Night->Evening, Winter->Fall). Heat maps use `order.rows` / `order.columns` and `row_field`.",
         "- `series` (combo charts) tells you which field is a bar vs line and which axis (`left`/`right`).",
         "- `caveats` should be shown (tooltip/footnote) - judges ask about limitations.",
         "- `scope`: `whole_dataset`, `window_A` (2015-04..2017-07), `window_B` (2025-10..2026-08), `both_windows`.", "",
         "## 3. Filters (handout requires >= 2)", "",
         "The 8 KPIs and Q1-Q10 are `filterable_via_cube: true`. The cube has one row per distinct combination of "
         "`primary_type, district, month, day_of_week, time_of_day, arrest, domestic` with a `crimes` count (dictionary-coded; decode with `lookups`). "
         "To filter: keep rows whose dim index is in the selected set, then sum `crimes` grouped by the dim you chart. "
         "Season = `lookups.season_of_month[month]`, year = `year_of_month`, category = `crime_category_of_type[primary_type]`. "
         "Arrest rate = sum(crimes where arrest=1) / sum(crimes). `python run_all.py` proves that unfiltered cube aggregation equals every handout chart exactly "
         "and that 25 random filter combinations equal the raw rows.",
         "Pseudo-code:", "```ts",
         "const keep = (i) => sel.type.has(cube.columns.primary_type[i]) && sel.district.has(cube.columns.district[i]);",
         "for (let i = 0; i < cube.rows; i++) if (keep(i)) agg[cube.columns.day_of_week[i]] += cube.columns.crimes[i];",
         "```",
         "Extra (`x_*`) charts are pre-computed for a fixed window and are **not** filterable; label them as such in the UI (e.g. a 'window A, unfiltered' badge).", "",
         "## 4. Gotchas", "",
         "- Q4 (season) is 2016 only; Q1 is Apr 2015-Jul 2017 only; K6 uses the same window. Everything else is the whole dataset.",
         "- K7 has `sensitivity_value` (excludes placeholder timestamps). Show the handout-literal `value` as the card and the sensitivity as a footnote.",
         "- Q6/Q9 raw arrest rates are confounded by crime-type mix; `x_arrest_tod_standardised` and `x_district_sir` are the corrected views. Linking the two is the strongest story.",
         "- Maps: `geo/` is window A only (window B has ~0% coordinates). Use any web-map tiles as a basemap; there are no boundary polygons in the data, so district/community-area shapes are not provided.",
         "- Missing values are `null`. District codes are numbers (24 distinct, incl. 31 and 61); community areas are codes without names.",
         "- Data are for display: do not recompute or round differently from the JSON. Percent fields end in `_pct` (0-100, not 0-1).", "",
         "## 5. Charts", "", "| id | handout | recommended type | scope | filterable | title |", "|---|---|---|---|---|---|"]
    for e in sorted(charts, key=lambda e: (not e["id"].startswith("q"), e["id"])):
        L.append(f"| `{e['id']}` | {e['handout_ref'] or ''} | {e['chart_type']} | {e['scope']} | {'yes' if e['filterable_via_cube'] else 'no'} | {e['title']} |")
    L += ["", "## 6. Suggested dashboard story (derived from `insights.json`, tier `headline`)", ""]
    for i in ins:
        if i["tier"] == "headline":
            L.append(f"- **{i['headline']}** -> charts: {', '.join('`'+c+'`' for c in i['charts'])}")
    L += ["", "## 7. Regenerating", "", "```bash", "pip install -r requirements.txt", "python run_all.py            # uses cached parquet", "python run_all.py --reload   # re-reads the xlsx (~4 min)", "pytest tests", "```", ""]
    (ROOT / "HANDOFF.md").write_text("\n".join(L), encoding="utf-8")

    # ---------------- analysis_report.md --------------------------------------------------------
    R = ["# TECHVERSE - Chicago Crimes: analysis report", "",
         "Generated from `export/` by `src/docs.py`. Every number below is read from the exported JSON.", "",
         "## 1. Problem and data", "",
         f"Source: {meth['source']['provenance']} File: `{meth['source']['file']}` (read-only; byte-identical after analysis - see `validate.py`).",
         f"Windows detected from data: A = {meth['windows']['A']['start']} to {meth['windows']['A']['end_exclusive']} (excl.), {meth['windows']['A']['records']:,} records; "
         f"B = {meth['windows']['B']['start']} to {meth['windows']['B']['end_exclusive']} (excl.), {meth['windows']['B']['records']:,} records; {meth['records_outside_windows']:,} records elsewhere.", "",
         "## 2. KPIs (handout definitions, whole dataset)", "", "| KPI | value | formula |", "|---|---|---|"]
    for k in kpis:
        v = f"{k['value']:,.2f}" if k["unit"] != "count" else f"{k['value']:,.0f}"
        R.append(f"| {k['id']} {k['label']} | {v} {'' if k['unit']=='count' else k['unit']} | {k['formula']} |")
    R += ["", "## 3. Cleaning log", "", "```json", json.dumps(_j(EXPORT / "cleaning_log.json"), indent=1), "```", "",
          "## 4. Assumptions and limitations", ""] + [f"- {a}" for a in meth["assumptions"]] + [""] + [f"- {a}" for a in meth["limitations"]] + [""]
    R += ["## 5. Findings", ""]
    for tier in ("headline", "supporting", "data_quality"):
        R.append(f"### {tier.replace('_', ' ').title()}")
        R.append("")
        for i in ins:
            if i["tier"] == tier:
                R += [f"**{i['headline']}**  ", i["text"], f"*Method:* {i['method']}" + (f" *Caveat:* {i['caveat']}" if i["caveat"] else ""), f"*Charts:* {', '.join(i['charts'])}", ""]
    R += ["## 6. Viva cheat-sheet: why each handout chart type", ""] + [f"- **{k.upper()}** - {v}" for k, v in WHY_CHART.items()]
    R += ["", "## 7. Likely judge questions", "",
          "- *Why did you change the dates?* 40% of Date cells were Excel datetimes with month/day swapped (only possible when day<=12); swapped back, they match Updated On and the handout's monthly chart (`cleaning_log.json`).",
          "- *Why two windows?* The file is a slice of a larger table; only two periods are near-complete (daily-count rule in `windows.py`). Whole-dataset KPIs still follow the handout.",
          "- *Why standardise arrest rates?* Because crime mix differs by hour and district; Simpson's paradox. See `arrest_simpson` and `arrest_district`.",
          "- *Why report effect sizes instead of p-values?* n is 10^5-10^6, so everything is 'significant'; Cohen's w, ratios and CIs say how big.",
          "- *What would change the conclusions?* Population denominators, complete data for window B, a flag for estimated dates.", ""]
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "analysis_report.md").write_text("\n".join(R), encoding="utf-8")
